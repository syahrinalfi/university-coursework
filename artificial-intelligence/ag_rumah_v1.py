def calculate_fitness(nilai_luas, nilai_prioritas, populasi, threshold):
    fitness = np.empty(populasi.shape[0])
    for i in range(populasi.shape[0]):
        prioritas = np.sum(populasi[i] * nilai_prioritas)
        luas = np.sum(populasi[i] * nilai_luas)
        if luas <= threshold:
            fitness[i] = prioritas
        else:
            fitness[i] = 0
    return fitness.astype(int)


